#!/usr/bin/env node

import { Command } from 'commander';
import { init, SUPPORTED_AI } from '../src/init.js';
import { verify } from '../src/verify.js';
import { probe } from '../src/probe.js';
import { compare } from '../src/compare.js';
import { run } from '../src/run.js';
import { history } from '../src/history.js';
import { iq } from '../src/iq.js';
import { readFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const pkg = JSON.parse(readFileSync(join(__dirname, '../package.json'), 'utf-8'));

const program = new Command();

program
  .name('ccfp')
  .description('AI Model Identity Fingerprinting Tool / AI 模型身份指纹识别工具')
  .version(pkg.version)
  .addHelpText('after', '\nExit codes: 0 ok · 1 error · 2 confidence below --fail-under, or a change with --fail-on-drift');

program
  .command('init')
  .description('Install the /fingerprint prompt for an AI assistant / 安装 /fingerprint 提示词')
  .option('--ai <type>', `Target AI (${SUPPORTED_AI.join(', ')}, all)`, 'claude')
  .option('--lang <language>', 'Language (zh, en)', 'zh')
  .option('--output <path>', 'Output directory path / 输出目录', '.')
  .option('--quick', 'Shorter probe set (about half the questions) / 快速探针集', false)
  .option('--force', 'Overwrite an existing file not generated by ccfingerprint / 强制覆盖', false)
  .action(async (options) => {
    await init(options);
  });

const verdictOptions = (cmd, outputDefault) => cmd
  .option('--lang <language>', 'Language (zh, en)', 'zh')
  .option('--output <path>', 'Markdown output file / Markdown 输出文件', outputDefault)
  .option('--baseline <report>', 'Reference report from the official API / 官方接口的基准报告')
  .option('--json', 'Print a JSON verdict instead of Markdown / 输出 JSON', false)
  .option('--html <path>', 'Also save a self-contained, shareable HTML report / 另存一份可分享的 HTML 报告')
  .option('--fail-under <score>', 'Exit with code 2 if the confidence is below this score / 可信度低于该值时退出码为 2');

verdictOptions(program
  .command('verify [report]')
  .description('Score a fingerprint report deterministically / 对指纹报告进行本地确定性评分'), 'ccfp-verdict.md')
  .action(async (report, options) => {
    await verify(report, options);
  });

verdictOptions(program
  .command('probe')
  .description('Probe an API endpoint directly (OpenAI-compatible or Anthropic) / 直接探测 API 端点')
  .requiredOption('--base-url <url>', 'Endpoint base URL, e.g. https://relay.example.com/v1')
  .requiredOption('--model <id>', 'Model ID to request, e.g. claude-opus-5-5')
  .option('--api <protocol>', 'openai (/v1/chat/completions) or anthropic (/v1/messages)', 'openai')
  .option('--api-key-env <name>', 'Environment variable holding the API key', 'CCFP_API_KEY')
  .option('--quick', 'Quick probe set: about half the requests / 快速模式，请求数约减半', false)
  .option('--runs <n>', 'Repeat the probe set n times to catch rotating routing / 重复 n 轮以发现轮换路由', '1')
  .option('--canary <n>', 'Identical tiny requests used to check prompt-token stability (0 = off)', '3')
  .option('--concurrency <n>', 'Parallel requests', '4')
  .option('--max-tokens <n>', 'max_tokens per request (anthropic default 2048; openai: not sent)')
  .option('--temperature <t>', 'Sampling temperature (not sent by default)')
  .option('--timeout <seconds>', 'Per-request timeout', '120')
  .option('--report <path>', 'Where to save the raw report / 原始报告保存位置', 'ccfp-report.json')
  .option('--history <file>', 'Append a summary line to this JSONL file and flag changes since the last run / 追加到历史文件并检查变化')
  .option('--fail-on-drift', 'Exit with code 2 if the endpoint changed since the last run in --history / 有变化时退出码为 2', false), 'ccfp-verdict.md')
  .action(async (options) => {
    await probe(options);
  });

program
  .command('iq')
  .description('Downgrade check (降智检测): fresh reasoning tasks, reasoning tokens, long context, output cap / 检测模型是否被降智')
  .option('--base-url <url>', 'Endpoint base URL, e.g. https://api.openai.com/v1')
  .option('--model <id>', 'Model ID to request (with --grade: the model you picked in the chat app)')
  .option('--api <protocol>', 'openai (/v1/chat/completions) or anthropic (/v1/messages)', 'openai')
  .option('--api-key-env <name>', 'Environment variable holding the API key', 'CCFP_API_KEY')
  .option('--level <set>', 'quick (12 tasks) | standard (23) | full (46); sheets default to quick')
  .option('--seed <n>', 'Task seed; use the same seed on the official API for a comparable baseline / 题目种子')
  .option('--rounds <n>', 'Repeat the task set n times to catch intermittent downgrades / 重复 n 轮', '1')
  .option('--context <tokens>', 'Needle-in-a-haystack prompt size, e.g. 32k or 128k; 0 = off (default by level: 8k / 32k / 100k)')
  .option('--long-output', 'Also check that a ~5k-token output is not cut short / 检查长输出是否被截断', false)
  .option('--reasoning-effort <level>', 'Send reasoning_effort (openai protocol), e.g. high')
  .option('--thinking-budget <tokens>', 'Enable extended thinking with this budget (anthropic protocol)')
  .option('--concurrency <n>', 'Parallel requests', '4')
  .option('--max-tokens <n>', 'max_tokens per request (anthropic default 8000; openai: not sent)')
  .option('--timeout <seconds>', 'Per-request timeout', '300')
  .option('--baseline <report>', 'ccfp iq report from the official API (ideally same --seed) / 官方接口的基准报告')
  .option('--report <path>', 'Where to save the raw report / 原始报告保存位置', 'ccfp-iq.json')
  .option('--from <report>', 'Re-score a saved raw report instead of calling the endpoint / 重新评分已有报告')
  .option('--sheet [file]', 'Write a paste-in task sheet for chat apps without an API (e.g. the ChatGPT web app) / 生成网页版自测题单')
  .option('--grade <reply>', 'Grade the chat app reply to a sheet (needs --seed) / 给网页版回复评分')
  .option('--history <file>', 'Append to this JSONL file and flag changes since the last run / 追加到历史文件并检查变化')
  .option('--fail-on-drift', 'Exit with code 2 if the result changed since the last run in --history', false)
  .option('--fail-on-downgrade', 'Exit with code 2 if the verdict is "downgraded" / 判定为降智时退出码为 2', false)
  .option('--fail-under <score>', 'Exit with code 2 if the score is below this / 得分低于该值时退出码为 2')
  .option('--lang <language>', 'Language (zh, en)', 'zh')
  .option('--output <path>', 'Markdown output file', 'ccfp-iq.md')
  .option('--json', 'Print JSON instead of Markdown', false)
  .option('--html <path>', 'Also save a shareable HTML report / 另存 HTML 报告')
  .action(async (options) => {
    await iq(options);
  });

program
  .command('compare <reports...>')
  .description('Compare several reports side by side (one per endpoint) / 多端点对比')
  .option('--lang <language>', 'Language (zh, en)', 'zh')
  .option('--output <path>', 'Markdown output file', 'ccfp-compare.md')
  .option('--baseline <report>', 'Reference report from the official API / 官方接口的基准报告')
  .option('--json', 'Print JSON instead of Markdown', false)
  .option('--html <path>', 'Also save a shareable HTML report / 另存 HTML 报告')
  .option('--fail-under <score>', 'Exit with code 2 if any endpoint scores below this')
  .action(async (reports, options) => {
    await compare(reports, options);
  });

const runOptions = (cmd) => cmd
  .requiredOption('--config <file>', 'JSON file listing the endpoints / 端点配置文件 (JSON)')
  .option('--lang <language>', 'Language (zh, en); overrides the config')
  .option('--out-dir <dir>', 'Where reports go (default from config, else ccfp-runs)')
  .option('--history <file>', 'History file (default <out-dir>/history.jsonl)')
  .option('--json', 'Print JSON instead of Markdown', false)
  .option('--fail-under <score>', 'Exit with code 2 if any endpoint scores below this')
  .option('--fail-on-drift', 'Exit with code 2 if any endpoint changed since its previous run', false);

runOptions(program
  .command('run')
  .description('Probe every endpoint in a config file, compare them and record history / 按配置文件一次检测多个端点'))
  .action(async (options) => {
    await run(options);
  });

runOptions(program
  .command('watch')
  .description('Same as run, repeated on a timer; flags endpoints that change between rounds / 定时重复检测并提示变化'))
  .requiredOption('--every <interval>', 'Interval between rounds: 30m, 6h, 1d …')
  .option('--times <n>', 'Stop after n rounds (default: run until stopped)')
  .action(async (options) => {
    await run(options, { watch: true });
  });

program
  .command('history [file]')
  .description('Show the probe history and what changed between runs / 查看历史与变化')
  .option('--lang <language>', 'Language (zh, en)', 'zh')
  .option('--last <n>', 'Rows per endpoint', '20')
  .option('--json', 'Print JSON instead of Markdown', false)
  .option('--html <path>', 'Also save a shareable HTML report / 另存 HTML 报告')
  .option('--fail-on-drift', 'Exit with code 2 if the latest run of any endpoint changed', false)
  .action(async (file, options) => {
    await history(file, options);
  });

program.parse();
