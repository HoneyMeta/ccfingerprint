#!/usr/bin/env node

import { Command } from 'commander';
import { init, SUPPORTED_AI } from '../src/init.js';
import { verify } from '../src/verify.js';
import { probe } from '../src/probe.js';
import { compare } from '../src/compare.js';
import { readFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const pkg = JSON.parse(readFileSync(join(__dirname, '../package.json'), 'utf-8'));

const program = new Command();

program
  .name('ccfp')
  .description('AI Model Identity Fingerprinting Tool / AI 模型身份指纹识别工具')
  .version(pkg.version)
  .addHelpText('after', '\nExit codes: 0 ok · 1 error · 2 confidence below --fail-under');

program
  .command('init')
  .description('Install the /fingerprint prompt for an AI assistant / 安装 /fingerprint 提示词')
  .option('--ai <type>', `Target AI (${SUPPORTED_AI.join(', ')}, all)`, 'claude')
  .option('--lang <language>', 'Language (zh, en)', 'zh')
  .option('--output <path>', 'Output directory path / 输出目录', '.')
  .option('--quick', 'Shorter probe set (about half the questions) / 快速探针集', false)
  .option('--force', 'Overwrite an existing file not generated by ccfingerprint / 强制覆盖', false)
  .action(async (options) => {
    await init(options);
  });

const verdictOptions = (cmd, outputDefault) => cmd
  .option('--lang <language>', 'Language (zh, en)', 'zh')
  .option('--output <path>', 'Markdown output file / Markdown 输出文件', outputDefault)
  .option('--baseline <report>', 'Reference report from the official API / 官方接口的基准报告')
  .option('--json', 'Print a JSON verdict instead of Markdown / 输出 JSON', false)
  .option('--fail-under <score>', 'Exit with code 2 if the confidence is below this score / 可信度低于该值时退出码为 2');

verdictOptions(program
  .command('verify [report]')
  .description('Score a fingerprint report deterministically / 对指纹报告进行本地确定性评分'), 'ccfp-verdict.md')
  .action(async (report, options) => {
    await verify(report, options);
  });

verdictOptions(program
  .command('probe')
  .description('Probe an API endpoint directly (OpenAI-compatible or Anthropic) / 直接探测 API 端点')
  .requiredOption('--base-url <url>', 'Endpoint base URL, e.g. https://relay.example.com/v1')
  .requiredOption('--model <id>', 'Model ID to request, e.g. claude-opus-5-5')
  .option('--api <protocol>', 'openai (/v1/chat/completions) or anthropic (/v1/messages)', 'openai')
  .option('--api-key-env <name>', 'Environment variable holding the API key', 'CCFP_API_KEY')
  .option('--quick', 'Quick probe set: about half the requests / 快速模式，请求数约减半', false)
  .option('--runs <n>', 'Repeat the probe set n times to catch rotating routing / 重复 n 轮以发现轮换路由', '1')
  .option('--canary <n>', 'Identical tiny requests used to check prompt-token stability (0 = off)', '3')
  .option('--concurrency <n>', 'Parallel requests', '4')
  .option('--max-tokens <n>', 'max_tokens per request (anthropic default 2048; openai: not sent)')
  .option('--temperature <t>', 'Sampling temperature (not sent by default)')
  .option('--timeout <seconds>', 'Per-request timeout', '120')
  .option('--report <path>', 'Where to save the raw report / 原始报告保存位置', 'ccfp-report.json'), 'ccfp-verdict.md')
  .action(async (options) => {
    await probe(options);
  });

program
  .command('compare <reports...>')
  .description('Compare several reports side by side (one per endpoint) / 多端点对比')
  .option('--lang <language>', 'Language (zh, en)', 'zh')
  .option('--output <path>', 'Markdown output file', 'ccfp-compare.md')
  .option('--baseline <report>', 'Reference report from the official API / 官方接口的基准报告')
  .option('--json', 'Print JSON instead of Markdown', false)
  .option('--fail-under <score>', 'Exit with code 2 if any endpoint scores below this')
  .action(async (reports, options) => {
    await compare(reports, options);
  });

program.parse();
